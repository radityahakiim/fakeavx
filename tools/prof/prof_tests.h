/*
 * The instructions fakeavx-prof measures and checks, one T() per line:
 *
 *   T(name, flags, instruction[; instruction...])
 *
 * Included by prof.S (which builds a benchmark loop and a single-shot check
 * function for each) and by fakeavx-prof.c (names and text). AT&T syntax.
 * Register conventions, set up identically for every test:
 *   %rsi        64-byte aligned 512-byte memory buffer (read and written)
 *   %ymm0-15    test data; %ymm6 holds small gather indices (dwords 0..7,
 *               odd dwords 0, so they are also valid qword indices); %ymm5
 *               is a mask; %ymm3 a blend selector
 *   %rax %rcx %rdx %r8-%r11   test data
 *   %rdi        reserved (loop counter / state pointer): never touch it
 * Group prefixes: mov, int, fp, cvt, shuf, mask (masked/gathers), lg
 * (legacy-encoded, trapping on Core 2), s41 (legacy SSE4.1: native on
 * Penryn, emulated on Merom/Kentsfield), mix (an AVX instruction together
 * with legacy SSE in one loop, as in code that is mostly SSE), ref (native
 * SSE, for comparison).
 * flags: 0, or NOCHK for results that differ between CPUs by design.
 */

